        output.Bytes |> should equal bytes
        retained |> should equal bytes
        output.BorrowedRangeCount |> should equal 1
        output.GeneratedRangeCount |> should equal 0

    [<Fact>]
    let ``downstream release does not change upstream stage retention`` () =
        let upstreamBytes = [| 1uy; 2uy; 3uy |]
        let emittedBytes = [| 24uy; 25uy; 26uy |]
        let stageAInput = input upstreamBytes false
        let stageAOutput = RecordingProcessorOutput(stageAInput)

        let stageA =
            { new IByteStreamProcessor with
                member _.ProcessAsync(input, output, _) =
                    writeBytes output emittedBytes
                    completed input.Bytes.Length }

        let stageAResult =
            stageA
                .ProcessAsync(stageAInput, stageAOutput, CancellationToken.None)
                .Result

        let stageARetained =
            ProcessorContract.getRetainedSuffix stageAInput stageAResult

        let stageBInput = input stageAOutput.Bytes false
        let stageBOutput = RecordingProcessorOutput(stageBInput)

        let stageB =
            { new IByteStreamProcessor with
                member _.ProcessAsync(_, _, _) = completed 0L }

        let stageBResult =
            stageB
                .ProcessAsync(stageBInput, stageBOutput, CancellationToken.None)
                .Result

        ProcessorContract.getRetainedSuffix stageBInput stageBResult
        |> fun retained -> retained.IsEmpty
        |> should equal true

        stageBInput.Bytes |> sequenceBytes |> should equal emittedBytes
        stageARetained |> sequenceBytes |> should equal upstreamBytes

    [<Fact>]
    let ``retained input is combined with new upstream bytes for the next invocation`` () =
        let firstInputBytes = [| 1uy; 2uy; 3uy |]
        let currentInput = input firstInputBytes false
        let firstOutput = RecordingProcessorOutput(currentInput)

        let retainingProcessor =
            { new IByteStreamProcessor with
                member _.ProcessAsync(input, _, _) = completed input.Bytes.Length }

        let firstResult =
            retainingProcessor
                .ProcessAsync(currentInput, firstOutput, CancellationToken.None)
                .Result

        let retained =
            ProcessorContract.getRetainedSuffix currentInput firstResult
            |> sequenceBytes

        let nextInput = input (Array.append retained [| 4uy; 5uy; 6uy |]) false
        let nextOutput = RecordingProcessorOutput(nextInput)
        let mutable observed = Array.empty<byte>

        let observingProcessor =
            { new IByteStreamProcessor with
                member _.ProcessAsync(input, _, _) =
                    observed <- sequenceBytes input.Bytes
                    completed 0L }

        let nextResult =
            observingProcessor
                .ProcessAsync(nextInput, nextOutput, CancellationToken.None)
                .Result

        ProcessorContract.getRetainedSuffix nextInput nextResult |> ignore
        observed |> should equal [| 1uy; 2uy; 3uy; 4uy; 5uy; 6uy |]

    [<Fact>]
    let ``processor can complete with empty final input`` () =
        let currentInput = input Array.empty true
        let output = RecordingProcessorOutput(currentInput)

        let processor =
            { new IByteStreamProcessor with
                member _.ProcessAsync(input, _, _) =
