namespace PipeL4.Tests

open System
open System.Buffers
open System.Threading
open System.Threading.Tasks
open FsUnit.Xunit
open PipeL4.Core
open Xunit

module ProcessorContractTests =
    let private sequenceBytes (input: ReadOnlySequence<byte>) =
        let bytes = Array.zeroCreate<byte> (int input.Length)
        input.CopyTo(bytes.AsSpan())
        bytes

    [<NoEquality; NoComparison>]
    type private RecordedRange =
        | Borrowed of ReadOnlySequence<byte>
        | Generated of byte array

    type private RecordingProcessorOutput(input: ProcessorInput) =
        let ranges = ResizeArray<RecordedRange>()
        let mutable writableBuffer = Array.empty<byte>
        let mutable hasWritableBuffer = false

        let allocate sizeHint =
            if sizeHint < 0 then
                invalidArg (nameof sizeHint) "Size hint cannot be negative."

            writableBuffer <- Array.zeroCreate<byte> (max sizeHint 1)
            hasWritableBuffer <- true
            writableBuffer

        member _.BorrowedRangeCount =
            ranges
            |> Seq.filter (function
                | Borrowed _ -> true
                | Generated _ -> false)
            |> Seq.length

        member _.GeneratedRangeCount =
            ranges
            |> Seq.filter (function
                | Borrowed _ -> false
                | Generated _ -> true)
            |> Seq.length

        member _.Bytes =
            ranges
            |> Seq.map (function
                | Borrowed bytes -> sequenceBytes bytes
                | Generated bytes -> bytes)
            |> Seq.toArray
            |> Array.concat

        interface IProcessorOutput with
            member _.AppendInput(offset, length) =
                ProcessorContract.getInputRange input offset length
                |> Borrowed
                |> ranges.Add

            member _.Advance(count) =
                if not hasWritableBuffer then
                    invalidOp "Cannot advance without requesting writable memory."

                if count < 0 || count > writableBuffer.Length then
                    invalidOp
                        $"Cannot advance {count} bytes in a buffer of {writableBuffer.Length} bytes."

                if count > 0 then
                    writableBuffer.AsSpan(0, count).ToArray()
                    |> Generated
                    |> ranges.Add

                writableBuffer <- Array.empty
                hasWritableBuffer <- false

            member _.GetMemory(sizeHint) = allocate sizeHint |> Memory<byte>

            member _.GetSpan(sizeHint) = (allocate sizeHint).AsSpan()

    let private input (bytes: byte array) isCompleted =
        { Bytes = ReadOnlySequence<byte>(bytes)
          IsCompleted = isCompleted }

    let private writeBytes (output: IProcessorOutput) (bytes: byte array) =
        if bytes.Length > 0 then
            let destination = output.GetSpan(bytes.Length)
            bytes.AsSpan().CopyTo(destination)
            output.Advance(bytes.Length)

    let private completed (retainedLength: int64) =
        ValueTask<ProcessorResult>({ RetainedLength = retainedLength })

    [<Fact>]
    let ``pass through appends runtime-owned input without a generated copy`` () =
        let bytes = [| 1uy; 2uy; 3uy; 4uy |]
        let currentInput = input bytes false
        let output = RecordingProcessorOutput(currentInput)

        let processor =
            { new IByteStreamProcessor with
                member _.ProcessAsync(input, output, _) =
                    output.AppendInput(0L, input.Bytes.Length)
                    completed 0L }

        let result =
            processor
                .ProcessAsync(currentInput, output, CancellationToken.None)
                .Result

        let retained = ProcessorContract.getRetainedSuffix currentInput result
        retained.IsEmpty |> should equal true
        output.Bytes |> should equal bytes
        output.BorrowedRangeCount |> should equal 1
        output.GeneratedRangeCount |> should equal 0

    [<Fact>]
    let ``processor can release input without producing output`` () =
        let currentInput = input [| 10uy; 20uy; 30uy |] false
        let output = RecordingProcessorOutput(currentInput)

        let processor =
            { new IByteStreamProcessor with
                member _.ProcessAsync(_, _, _) = completed 0L }

        let result =
            processor
                .ProcessAsync(currentInput, output, CancellationToken.None)
                .Result

        ProcessorContract.getRetainedSuffix currentInput result
        |> fun retained -> retained.IsEmpty
        |> should equal true

        output.Bytes |> should be Empty

    [<Fact>]
    let ``processor can retain the entire input while upstream is open`` () =
        let bytes = [| 1uy; 2uy; 3uy |]
        let currentInput = input bytes false
        let output = RecordingProcessorOutput(currentInput)

        let processor =
            { new IByteStreamProcessor with
                member _.ProcessAsync(input, _, _) = completed input.Bytes.Length }

        let result =
            processor
                .ProcessAsync(currentInput, output, CancellationToken.None)
                .Result

        ProcessorContract.getRetainedSuffix currentInput result
        |> sequenceBytes
        |> should equal bytes

        output.Bytes |> should be Empty

    [<Fact>]
    let ``processor can resolve a prefix and retain only the suffix`` () =
        let bytes = [| 1uy; 2uy; 3uy; 4uy; 5uy; 6uy |]
        let currentInput = input bytes false
        let output = RecordingProcessorOutput(currentInput)

        let processor =
            { new IByteStreamProcessor with
                member _.ProcessAsync(_, output, _) =
                    output.AppendInput(0L, 4L)
                    completed 2L }

        let result =
            processor
                .ProcessAsync(currentInput, output, CancellationToken.None)
                .Result

        let retained =
            ProcessorContract.getRetainedSuffix currentInput result
            |> sequenceBytes

        output.Bytes |> should equal bytes[..3]
        retained |> should equal bytes[4..]
        Array.append retained [| 7uy |] |> should equal [| 5uy; 6uy; 7uy |]

    [<Fact>]
    let ``generated output can be shorter than input`` () =
        let currentInput = input [| 1uy; 2uy; 3uy |] false
        let output = RecordingProcessorOutput(currentInput)

        let processor =
            { new IByteStreamProcessor with
                member _.ProcessAsync(_, output, _) =
                    writeBytes output [| 9uy |]
                    completed 0L }

        let result =
            processor
                .ProcessAsync(currentInput, output, CancellationToken.None)
                .Result

        ProcessorContract.getRetainedSuffix currentInput result |> ignore
        output.Bytes |> should equal [| 9uy |]

    [<Fact>]
    let ``generated output can be longer than input`` () =
        let currentInput = input [| 1uy; 2uy |] false
        let output = RecordingProcessorOutput(currentInput)

        let processor =
            { new IByteStreamProcessor with
                member _.ProcessAsync(_, output, _) =
                    writeBytes output [| 9uy; 10uy; 11uy; 12uy; 13uy |]
                    completed 0L }

        let result =
            processor
                .ProcessAsync(currentInput, output, CancellationToken.None)
                .Result

        ProcessorContract.getRetainedSuffix currentInput result |> ignore
        output.Bytes |> should equal [| 9uy; 10uy; 11uy; 12uy; 13uy |]

    [<Fact>]
    let ``borrowed and generated ranges form one ordered byte stream`` () =
        let currentInput = input [| 1uy; 3uy |] false
        let output = RecordingProcessorOutput(currentInput)

        let processor =
            { new IByteStreamProcessor with
                member _.ProcessAsync(_, output, _) =
                    output.AppendInput(0L, 1L)
                    writeBytes output [| 2uy |]
                    output.AppendInput(1L, 1L)
                    completed 0L }

        let result =
            processor
                .ProcessAsync(currentInput, output, CancellationToken.None)
                .Result

        ProcessorContract.getRetainedSuffix currentInput result |> ignore
        output.Bytes |> should equal [| 1uy; 2uy; 3uy |]
        output.BorrowedRangeCount |> should equal 2
        output.GeneratedRangeCount |> should equal 1

    [<Fact>]
    let ``processor can emit generated output while retaining all input`` () =
        let inputBytes = [| 1uy; 2uy; 3uy |]
        let generatedBytes = [| 24uy; 25uy; 26uy |]
        let currentInput = input inputBytes false
        let output = RecordingProcessorOutput(currentInput)

        let processor =
            { new IByteStreamProcessor with
                member _.ProcessAsync(input, output, _) =
                    writeBytes output generatedBytes
                    completed input.Bytes.Length }

        let result =
            processor
                .ProcessAsync(currentInput, output, CancellationToken.None)
                .Result

        let retained =
            ProcessorContract.getRetainedSuffix currentInput result
            |> sequenceBytes

        output.Bytes |> should equal generatedBytes
        retained |> should equal inputBytes
        output.GeneratedRangeCount |> should equal 1

    [<Fact>]
    let ``processor can emit and retain the same input`` () =
        let bytes = [| 1uy; 2uy; 3uy |]
        let currentInput = input bytes false
        let output = RecordingProcessorOutput(currentInput)

        let processor =
            { new IByteStreamProcessor with
                member _.ProcessAsync(input, output, _) =
                    output.AppendInput(0L, input.Bytes.Length)
                    completed input.Bytes.Length }

        let result =
            processor
