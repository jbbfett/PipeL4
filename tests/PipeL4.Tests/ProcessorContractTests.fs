        ProcessorContract.getRetainedSuffix currentInput result
        |> fun retained -> retained.IsEmpty
        |> should equal true

    [<Fact>]
    let ``processor receives retained input with upstream completion`` () =
        let bytes = [| 5uy; 6uy |]
        let currentInput = input bytes true
        let output = RecordingProcessorOutput(currentInput)

        let processor =
            { new IByteStreamProcessor with
                member _.ProcessAsync(input, output, _) =
                    input.IsCompleted |> should equal true
                    output.AppendInput(0L, input.Bytes.Length)
                    completed 0L }

        let result =
            processor
                .ProcessAsync(currentInput, output, CancellationToken.None)
