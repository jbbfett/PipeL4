        output.Bytes |> should equal bytes

    [<Fact>]
    let ``retained length must describe a valid suffix`` () =
        let openInput = input [| 1uy; 2uy; 3uy |] false

        for retainedLength in [ -1L; 4L ] do
            (fun () ->
                ProcessorContract.getRetainedSuffix
                    openInput
                    { RetainedLength = retainedLength }
                |> ignore)
            |> should throw typeof<InvalidOperationException>

        let completedInput = input [| 1uy; 2uy; 3uy |] true

        (fun () ->
            ProcessorContract.getRetainedSuffix
                completedInput
                { RetainedLength = 1L }
            |> ignore)
        |> should throw typeof<InvalidOperationException>

    [<Fact>]
    let ``borrowed output range must belong to the current input`` () =
        let currentInput = input [| 1uy; 2uy; 3uy |] false

        for offset, length in [ -1L, 1L; 0L, -1L; 2L, 2L ] do
            let output = RecordingProcessorOutput(currentInput) :> IProcessorOutput

            (fun () -> output.AppendInput(offset, length))
            |> should throw typeof<InvalidOperationException>

    [<Fact>]
    let ``processor can suspend asynchronously without a control signal`` () =
        task {
            let release =
                TaskCompletionSource<unit>(TaskCreationOptions.RunContinuationsAsynchronously)

            let bytes = [| 21uy; 22uy |]
            let currentInput = input bytes false
            let output = RecordingProcessorOutput(currentInput)

            let processor =
                { new IByteStreamProcessor with
                    member _.ProcessAsync(input, output, _) =
                        ValueTask<ProcessorResult>(
                            task {
                                do! release.Task
                                output.AppendInput(0L, input.Bytes.Length)
                                return { RetainedLength = 0L }
                            }
                        ) }

            let operation =
                processor.ProcessAsync(currentInput, output, CancellationToken.None)

            operation.IsCompleted |> should equal false
            release.SetResult(())

            let! result = operation.AsTask()
            ProcessorContract.getRetainedSuffix currentInput result |> ignore
            output.Bytes |> should equal bytes
        }

    [<Fact>]
    let ``processor failure remains observable`` () =
        task {
            let expected = InvalidOperationException("processor failed")

            let processor =
                { new IByteStreamProcessor with
                    member _.ProcessAsync(_, _, _) =
                        ValueTask<ProcessorResult>(Task.FromException<ProcessorResult>(expected)) }

            let currentInput = input [| 1uy |] false
            let output = RecordingProcessorOutput(currentInput)
            let operation = processor.ProcessAsync(currentInput, output, CancellationToken.None)
            let mutable observed = None

            try
                let! _ = operation.AsTask()
                ()
            with error ->
                observed <- Some error

            match observed with
            | Some error -> Object.ReferenceEquals(error, expected) |> should equal true
            | None -> failwith "Expected the processor operation to fail."
        }
