namespace PipeL4.Tests

open System
open System.Buffers
open System.Threading
open FsUnit.Xunit
open PipeL4.Plugins
open Xunit

module FunctionalProcessorApiTests =
    type private Segment(memory: ReadOnlyMemory<byte>) =
        inherit ReadOnlySequenceSegment<byte>()

        do base.Memory <- memory

        member this.Append(next: Segment) =
            next.RunningIndex <- this.RunningIndex + int64 this.Memory.Length
            this.Next <- next

    [<NoEquality; NoComparison>]
    type private Emission =
        | Input of offset: int64 * length: int64 * bytes: ReadOnlySequence<byte>
        | Bytes of ReadOnlyMemory<byte>

    // Records the public output boundary without a functional adapter or pipeline execution.
    type private RecordingOutput(input: ReadOnlySequence<byte>) =
        let emissions = ResizeArray<Emission>()
        let sizeHints = ResizeArray<int>()
        let advances = ResizeArray<int>()
        let mutable writable = Memory<byte>.Empty

        let getMemory sizeHint =
            sizeHints.Add sizeHint
            writable <- Memory<byte>(Array.zeroCreate<byte> (max 1 sizeHint))
            writable

        member _.Emissions = emissions.ToArray()
        member _.SizeHints = sizeHints.ToArray()
        member _.Advances = advances.ToArray()

        member _.Bytes =
            emissions
            |> Seq.collect (function
                | Input(_, _, sequence) -> sequence.ToArray()
                | Bytes memory -> memory.ToArray())
            |> Seq.toArray

        interface IProcessorOutput with
            member _.AppendInput(offset, length) =
                emissions.Add(Input(offset, length, input.Slice(offset, length)))

            member _.GetSpan(sizeHint) = (getMemory sizeHint).Span
            member _.GetMemory(sizeHint) = getMemory sizeHint

            member _.Advance(count) =
                advances.Add count
                emissions.Add(Bytes(Memory<byte>.op_Implicit(writable.Slice(0, count))))
                writable <- Memory<byte>.Empty

    let private connectionState =
        { new IConnectionState with
            member _.GetOrAdd<'T>(_: string, factory: unit -> 'T) : 'T = factory ()
            member _.TryGet<'T>(_: string) : 'T option = None }

    let private context input output =
        { Input = input
          IsCompleted = false
          Output = output
          CancellationToken = CancellationToken.None
          ConnectionState = connectionState }

    [<Fact>]
    let ``context and repeated input emission preserve segments and backing memory`` () =
        let firstMemory = ReadOnlyMemory<byte>([| 1uy; 2uy; 3uy |])
        let lastMemory = ReadOnlyMemory<byte>([| 4uy; 5uy; 6uy |])
        let first = Segment(firstMemory)
        let last = Segment(lastMemory)
        first.Append last
        let input = ReadOnlySequence<byte>(first, 0, last, last.Memory.Length)
        let output = RecordingOutput(input)
        let ctx = context input output

        ctx.Input.IsSingleSegment |> should equal false
        ctx.Input.Start.Equals(input.Start) |> should equal true
        ctx.Input.End.Equals(input.End) |> should equal true

        emitInput ctx 1L 4L
        emitInput ctx 1L 4L
        emitInput ctx input.Length 0L

        output.Bytes |> should equal [| 2uy; 3uy; 4uy; 5uy; 2uy; 3uy; 4uy; 5uy |]
        output.SizeHints |> should be Empty
        output.Advances |> should be Empty

        for emission in output.Emissions[..1] do
            match emission with
            | Input(offset, length, sequence) ->
                offset |> should equal 1L
                length |> should equal 4L
                sequence.IsSingleSegment |> should equal false
                let segments = ResizeArray<ReadOnlyMemory<byte>>()
                for segment in sequence do
                    segments.Add segment
                segments.Count |> should equal 2
                segments[0].Equals(firstMemory.Slice(1)) |> should equal true
                segments[1].Equals(lastMemory.Slice(0, 2)) |> should equal true
            | Bytes _ -> failwith "Expected input-backed output."

    [<Fact>]
    let ``generated bytes copy directly to the output writer in mixed emission order`` () =
        let input = ReadOnlySequence<byte>([| 1uy; 7uy |])
        let output = RecordingOutput(input)
        let ctx = context input output
        let generated = [| 2uy; 3uy |]
        let sliced = ReadOnlyMemory<byte>([| 99uy; 4uy; 99uy |], 1, 1)

        emitInput ctx 0L 1L
        emitBytes ctx (ReadOnlySpan<byte>(generated))
        emitBytes ctx sliced.Span
        emitBytes ctx (ReadOnlySpan<byte>.Empty)
        emitBytes ctx (ReadOnlySpan<byte>(Array.empty<byte>))

        // The original advanced writer capabilities remain available through the context.
        let span = ctx.Output.GetSpan(1)
        span[0] <- 5uy
        ctx.Output.Advance(1)
        let memory = ctx.Output.GetMemory(1)
        memory.Span[0] <- 6uy
        ctx.Output.Advance(1)
        emitInput ctx 1L 1L

        generated.AsSpan().Clear()
        output.Bytes |> should equal [| 1uy; 2uy; 3uy; 4uy; 5uy; 6uy; 7uy |]
        output.SizeHints |> should equal [| 2; 1; 1; 1 |]
        output.Advances |> should equal [| 2; 1; 1; 1 |]

        match output.Emissions with
        | [| Input _; Bytes _; Bytes _; Bytes _; Bytes _; Input _ |] -> ()
        | _ -> failwith "Expected mixed output in call order."

    [<Fact>]
    let ``result helpers only select retention and do not emit or validate input`` () =
        let input = ReadOnlySequence<byte>([| 1uy; 2uy; 3uy |])
        let output = RecordingOutput(input)
        let ctx = context input output

        releaseAll.RetainedLength |> should equal 0L
        (retainSuffix 0L).RetainedLength |> should equal 0L
        (retainSuffix 2L).RetainedLength |> should equal 2L
        // Validation still belongs to the runtime, including out-of-range and EOF retention.
        (retainSuffix -1L).RetainedLength |> should equal -1L
        (retainSuffix 4L).RetainedLength |> should equal 4L
        output.Emissions |> should be Empty

        emitInput ctx 0L ctx.Input.Length
        let retained: ProcessorResult = retainSuffix ctx.Input.Length
        retained.RetainedLength |> should equal 3L
        output.Bytes |> should equal [| 1uy; 2uy; 3uy |]
        releaseAll.RetainedLength |> should equal 0L
        output.Emissions.Length |> should equal 1

    [<Fact>]
    let ``contexts expose normal completion cancellation and the existing state view`` () =
        use cancellation = new CancellationTokenSource()
        let input = ReadOnlySequence<byte>.Empty
        let output = RecordingOutput(input)
        let createContext: CreateContext = { ConnectionState = connectionState }
        let ctx =
            { context input output with
                IsCompleted = true
                CancellationToken = cancellation.Token }

        Assert.Same(createContext.ConnectionState, ctx.ConnectionState)
        Assert.Same(output, ctx.Output)
        ctx.IsCompleted |> should equal true
        ctx.CancellationToken |> should equal cancellation.Token
        cancellation.Cancel()
        ctx.CancellationToken.IsCancellationRequested |> should equal true

    [<Fact>]
    let ``helpers preserve output failures without wrapping them`` () =
        let expected = InvalidOperationException("output failed")
        let failingOutput =
            { new IProcessorOutput with
                member _.AppendInput(_, _) = raise expected
                member _.GetSpan(_) =
                    raise expected
                    Span<byte>.Empty
                member _.GetMemory(_) = raise expected
                member _.Advance(_) = raise expected }

        let ctx = context ReadOnlySequence<byte>.Empty failingOutput
        let inputError = Assert.Throws<InvalidOperationException>(fun () -> emitInput ctx 0L 1L)
        let bytesError =
            Assert.Throws<InvalidOperationException>(fun () ->
                emitBytes ctx (ReadOnlySpan<byte>([| 1uy |])))
        Assert.Same(expected, inputError)
        Assert.Same(expected, bytesError)

    [<Fact>]
    let ``functional signatures retain strongly typed local state and infer process context`` () =
        let create () = ref 0L
        let createWithContext (ctx: CreateContext) = ctx.ConnectionState, ref 0L

        let handle ctx =
            emitInput ctx 0L ctx.Input.Length
            releaseAll

        let handleWithState ctx (state: int64 ref) =
            state.Value <- state.Value + ctx.Input.Length
            emitInput ctx 0L ctx.Input.Length
            releaseAll

        let dispose (state: int64 ref) = state.Value <- 0L
        let _: unit -> int64 ref = create
        let _: CreateContext -> IConnectionState * int64 ref = createWithContext
        let _: ProcessContext -> ProcessorResult = handle
        let _: ProcessContext -> int64 ref -> ProcessorResult = handleWithState
        let _: int64 ref -> unit = dispose

        let input = ReadOnlySequence<byte>([| 1uy |])
        let output = RecordingOutput(input)
        let ctx = context input output
        let state = create ()
        (handle ctx).RetainedLength |> should equal 0L
        (handleWithState ctx state).RetainedLength |> should equal 0L
        state.Value |> should equal 1L
